package com.datadoghq.profiler.wallclock;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.datadoghq.profiler.CStackAwareAbstractProfilerTest;
import com.datadoghq.profiler.JfrFrame;
import com.datadoghq.profiler.JfrStackTrace;
import com.datadoghq.profiler.Platform;
import com.datadoghq.profiler.junit.CStack;
import java.util.Map;
import java.util.TreeMap;
import java.util.concurrent.FutureTask;
import org.junit.jupiter.api.TestTemplate;
import org.junit.jupiter.params.provider.ValueSource;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.Label;
import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;

/** Checks carrier recovery for compiled methods near the JVM's parameter-slot limit. */
public class HighArityVirtualThreadStackTest extends CStackAwareAbstractProfilerTest {
  private static final String GENERATED = "com/datadoghq/profiler/generated/HighArityContinuation";
  private static final int REFERENCES = 254;
  private static final int DEPTH = 16;

  /** Enables the park path in generated bytecode; on during warm-up so that path is compiled. */
  public static volatile boolean parking;

  private static volatile StackTraceElement[] logicalStack;

  /** Keeps the generated recursive return values live. */
  public static volatile int sink;

  /** Selects the VM walker with carrier recovery enabled. */
  public HighArityVirtualThreadStackTest(@CStack String cstack) {
    super(cstack);
  }

  @Override
  protected boolean isPlatformSupported() {
    return Platform.isJavaVersionAtLeast(21)
        && !Platform.isJ9()
        && !Platform.isZing()
        && !(isInCI() && Platform.isMusl() && !Platform.isAarch64());
  }

  @Override
  protected String getProfilerCommand() {
    return "wall=1ms,walltpt=64,filter=,jstackdepth=512";
  }

  /** Requires compiled, partially thawed samples to recover the carrier without pointer errors. */
  @TestTemplate
  @ValueSource(strings = {"vmx"})
  public void retainsCarrierWithMoreThan128StackArgumentWords() throws Exception {
    waitForProfilerReady(2_000);
    Runnable workload = new Loader().workload();
    // Warm up with the park path taken: a never-taken branch compiles to an uncommon trap,
    // and enabling it later would deoptimize the leaf during the sampling window.
    parking = true;
    // The generated recursive method has no back edge, so it cannot be an OSR entry.
    for (int i = 0; i < 2_000; i++) workload.run();
    // Warm-up ran on a platform thread; capture the virtual thread's stack instead.
    logicalStack = null;
    FutureTask<Void> task =
        new FutureTask<>(
            () -> {
              long deadline = System.nanoTime() + 3_000_000_000L;
              while (System.nanoTime() < deadline) workload.run();
              return null;
            });
    Thread worker =
        (Thread) Thread.class.getMethod("startVirtualThread", Runnable.class).invoke(null, task);
    try {
      worker.join(10_000);
      assertFalse(worker.isAlive(), "The high-arity workload did not finish");
      task.get();
    } finally {
      parking = false;
      worker.interrupt();
      stopProfiler();
    }
    assertTrue(logicalStack != null, "The high-arity workload did not capture its logical stack");
    int recursion = 0;
    for (StackTraceElement frame : logicalStack) {
      if (GENERATED.replace('/', '.').equals(frame.getClassName())
          && "recursive".equals(frame.getMethodName())) recursion++;
    }
    assertEquals(DEPTH + 1, recursion, "The JVM must retain the recursive callers");
    assertTrue(
        profiler.getDebugCounters().getOrDefault("walkvm_cont_barrier_hit", 0L) > 0,
        "The workload must exercise a continuation return barrier");
    // First offending stack per assertion: [0] carrier count, [1] truncation, [2] continuation
    // error.
    String[] firstBadStack = {null, null, null};
    String warmupThread = Thread.currentThread().getName();
    Map<String, Integer> excludedBreaks = new TreeMap<>();
    int[] counts =
        reduceEvents(
            "datadog.MethodSample",
            () -> new int[5],
            (count, sample) -> {
              String thread = sample.getThreadName("eventThread");
              assertNotNull(thread, "MethodSample must name its thread");
              // Warm-up runs on this platform thread and has no continuation to recover.
              if (warmupThread.equals(thread)) return;
              JfrStackTrace trace = sample.getStackTrace();
              boolean compiled = false;
              boolean outer = false;
              int carriers = 0;
              int errors = 0;
              boolean crossedBoundary = false;
              String otherBreak = null;
              for (JfrFrame frame : trace.frames()) {
                if (GENERATED.replace('/', '.').equals(frame.className())) {
                  compiled |=
                      "recursive".equals(frame.methodName())
                          && ("JIT compiled".equals(frame.typeDescription())
                              || "C1 compiled".equals(frame.typeDescription()));
                  outer |= "run".equals(frame.methodName());
                }
                if ("java.util.concurrent.ForkJoinWorkerThread".equals(frame.className())
                    && "run".equals(frame.methodName())) carriers++;
                crossedBoundary |= isCarrierSideFrame(frame);
                if (frame.methodName() != null && frame.methodName().startsWith("break_cont_"))
                  errors++;
                else if (frame.methodName() != null && frame.methodName().startsWith("break_"))
                  otherBreak = frame.methodName();
              }
              if (compiled && !outer) {
                // Only a walk that stopped before reaching the carrier is outside this test's
                // scope.
                if (otherBreak != null && !crossedBoundary && errors == 0 && carriers == 0) {
                  excludedBreaks.merge(otherBreak, 1, Integer::sum);
                  count[4]++;
                  return;
                }
                count[0]++;
                count[1] += errors;
                if (errors > 0 && firstBadStack[2] == null)
                  firstBadStack[2] = sample.getStackTraceString();
                if (carriers != 1) {
                  count[2]++;
                  if (firstBadStack[0] == null) firstBadStack[0] = sample.getStackTraceString();
                }
                if (!trace.isTruncated()) {
                  count[3]++;
                  if (firstBadStack[1] == null) firstBadStack[1] = sample.getStackTraceString();
                }
              }
            });
    System.out.println(
        "High-arity compiled partial samples="
            + counts[0]
            + " continuationErrors="
            + counts[1]
            + " stopsBeforeBoundary="
            + counts[4]
            + " "
            + excludedBreaks);
    assertTrue(counts[0] > 0, "No compiled high-arity sample left callers frozen");
    assertEquals(
        0,
        counts[1],
        "High-arity carrier recovery rejected valid argument metadata\n" + firstBadStack[2]);
    assertEquals(
        0, counts[2], "High-arity samples must retain exactly one carrier\n" + firstBadStack[0]);
    assertEquals(
        0, counts[3], "Skipped frozen callers must remain marked truncated\n" + firstBadStack[1]);
  }

  /** Frames below the continuation entry, present only once the walk reached the carrier. */
  private static boolean isCarrierSideFrame(JfrFrame frame) {
    return ("jdk.internal.vm.Continuation".equals(frame.className())
            && "run".equals(frame.methodName()))
        || ("java.lang.VirtualThread".equals(frame.className())
            && "runContinuation".equals(frame.methodName()));
  }

  /** Captures the JVM's logical callers once, independently of the profiler's physical walk. */
  public static void captureLogicalStack() {
    if (logicalStack == null) logicalStack = Thread.currentThread().getStackTrace();
  }

  /** Generates a legal 255-slot static signature: one int and 254 references. */
  private static final class Loader extends ClassLoader {
    private Loader() {
      super(HighArityVirtualThreadStackTest.class.getClassLoader());
    }

    /**
     * Defines high-arity recursion without a source signature containing hundreds of parameters.
     */
    private Runnable workload() throws Exception {
      StringBuilder descriptor = new StringBuilder("(I");
      for (int i = 0; i < REFERENCES; i++) descriptor.append("Ljava/lang/Object;");
      descriptor.append(")I");
      String signature = descriptor.toString();
      String owner = HighArityVirtualThreadStackTest.class.getName().replace('.', '/');
      ClassWriter cw = new ClassWriter(ClassWriter.COMPUTE_FRAMES | ClassWriter.COMPUTE_MAXS);
      cw.visit(
          Opcodes.V1_8,
          Opcodes.ACC_PUBLIC,
          GENERATED,
          null,
          "java/lang/Object",
          new String[] {"java/lang/Runnable"});
      MethodVisitor mv = cw.visitMethod(Opcodes.ACC_PUBLIC, "<init>", "()V", null, null);
      mv.visitCode();
      mv.visitVarInsn(Opcodes.ALOAD, 0);
      mv.visitMethodInsn(Opcodes.INVOKESPECIAL, "java/lang/Object", "<init>", "()V", false);
      mv.visitInsn(Opcodes.RETURN);
      mv.visitMaxs(0, 0);
      mv.visitEnd();
      mv = cw.visitMethod(Opcodes.ACC_PUBLIC, "run", "()V", null, null);
      mv.visitCode();
      mv.visitIntInsn(Opcodes.SIPUSH, DEPTH);
      for (int i = 0; i < REFERENCES; i++) mv.visitVarInsn(Opcodes.ALOAD, 0);
      mv.visitMethodInsn(Opcodes.INVOKESTATIC, GENERATED, "recursive", signature, false);
      mv.visitFieldInsn(Opcodes.PUTSTATIC, owner, "sink", "I");
      mv.visitInsn(Opcodes.RETURN);
      mv.visitMaxs(0, 0);
      mv.visitEnd();
      mv =
          cw.visitMethod(
              Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC, "recursive", signature, null, null);
      mv.visitCode();
      Label leaf = new Label();
      mv.visitVarInsn(Opcodes.ILOAD, 0);
      mv.visitJumpInsn(Opcodes.IFEQ, leaf);
      mv.visitVarInsn(Opcodes.ILOAD, 0);
      mv.visitInsn(Opcodes.ICONST_1);
      mv.visitInsn(Opcodes.ISUB);
      for (int i = 1; i <= REFERENCES; i++) mv.visitVarInsn(Opcodes.ALOAD, i);
      mv.visitMethodInsn(Opcodes.INVOKESTATIC, GENERATED, "recursive", signature, false);
      mv.visitVarInsn(Opcodes.ALOAD, REFERENCES);
      mv.visitMethodInsn(
          Opcodes.INVOKESTATIC,
          "java/lang/System",
          "identityHashCode",
          "(Ljava/lang/Object;)I",
          false);
      mv.visitInsn(Opcodes.IXOR);
      mv.visitInsn(Opcodes.IRETURN);
      mv.visitLabel(leaf);
      Label warmup = new Label();
      mv.visitFieldInsn(Opcodes.GETSTATIC, owner, "parking", "Z");
      mv.visitJumpInsn(Opcodes.IFEQ, warmup);
      mv.visitMethodInsn(Opcodes.INVOKESTATIC, owner, "captureLogicalStack", "()V", false);
      mv.visitLdcInsn(500_000L);
      mv.visitMethodInsn(
          Opcodes.INVOKESTATIC,
          "java/util/concurrent/locks/LockSupport",
          "parkNanos",
          "(J)V",
          false);
      // Unroll the sampling window in the high-arity frame itself. A bytecode loop
      // could compile as an OSR entry, whose nmethod has no stack arguments.
      mv.visitInsn(Opcodes.ICONST_1);
      for (int i = 0; i < 512; i++) {
        mv.visitMethodInsn(Opcodes.INVOKESTATIC, "java/lang/System", "nanoTime", "()J", false);
        mv.visitInsn(Opcodes.L2I);
        mv.visitInsn(Opcodes.IXOR);
      }
      mv.visitInsn(Opcodes.IRETURN);
      mv.visitLabel(warmup);
      mv.visitInsn(Opcodes.ICONST_1);
      mv.visitInsn(Opcodes.IRETURN);
      mv.visitMaxs(0, 0);
      mv.visitEnd();
      cw.visitEnd();
      byte[] bytes = cw.toByteArray();
      return (Runnable)
          defineClass(GENERATED.replace('/', '.'), bytes, 0, bytes.length)
              .getDeclaredConstructor()
              .newInstance();
    }
  }
}
